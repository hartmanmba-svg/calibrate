export async function seedCards(): Promise<{ seeded: boolean; count: number; message: string }> {
  const admin = createAdminClient()

  // Check if any cards already exist
  const { count, error: countError } = await admin
    .from('cards')
    .select('*', { count: 'exact', head: true })

  if (countError) {
    throw new Error(`Failed to check card count: ${countError.message}`)
  }

  if ((count ?? 0) > 0) {
    return {
      seeded: false,
      count: count ?? 0,
      message: `Database already has ${count} cards — seed skipped.`,
    }
  }

  // Insert all seed cards (legacy data — schema may differ from production)
  const { error: insertError } = await admin.from('cards').insert(SEED_CARDS)

  if (insertError) {
    throw new Error(`Failed to seed cards: ${insertError.message}`)
  }

  return {
    seeded: true,
    count: SEED_CARDS.length,
    message: `Successfully seeded ${SEED_CARDS.length} cards.`,
  }
}
